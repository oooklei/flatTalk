def write_xlsx(path: Path, items: list[dict], sheet_name: str = "QA") -> None:
    wb = Workbook()
    ws = wb.active
    ws.title = sheet_name
    headers = ["id", "category", "question", "answer", "source", "source_id", "tags"]
    ws.append(headers)
    for it in items:
        ws.append(
            [
                it.get("id"),
                it.get("category"),
                it.get("question"),
                it.get("answer"),
                it.get("source"),
                it.get("source_id"),
                ",".join(it.get("tags") or []),
            ]
        )
    ws2 = wb.create_sheet("分类统计")
    ws2.append(["category", "count"])
    c = Counter(it.get("category") for it in items)
    for k, v in sorted(c.items(), key=lambda x: (-x[1], x[0] or "")):
        ws2.append([k, v])
    path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(path)


