def build_guide_readme(qa_count: int) -> None:
    forms = sorted(p.name for p in FORM_MD.glob("*.md"))
    matters = sorted(p.name for p in MATTER_DIR.glob("*.md"))
    lines = [
        "# 广西养老办事指引知识库",
        "",
        "从政策原文办理流程与配套申请表提炼，供老年人AI办事指引智能体检索使用。",
        "",
        "## 目录说明",
        "",
        "| 路径 | 内容 |",
        "|------|------|",
        "| [00-事项索引.md](./00-事项索引.md) | 办事项一览 |",
        "| [事项/](./事项/) | 结构化办事指引（条件/材料/步骤/窗口/时限/依据） |",
        "| [表格说明/](./表格说明/) | 申请表、告知书等字段说明 |",
        "| [QA/](./QA/) | 办事问答数据集 |",
        "",
        f"办事项 **{len(matters)}** 个；表格说明 **{len(forms)}** 份；QA **{qa_count}** 条。",
        "",
        "## 回答约束",
        "",
        "- 不替代窗口审核；地方细则与窗口清单优先。",
        "- 不编造未在政策中写明的金额、时限。",
        "- 集中照护现行依据为桂民规〔2025〕1号，勿再用已废止的桂民规〔2024〕2号作为办理依据。",
        "",
        "## 事项清单",
        "",
    ]
    for name in matters:
        lines.append(f"- [{name}](./事项/{name})")
    lines.extend(["", "## 表格说明清单", ""])
    for name in forms:
        lines.append(f"- [{name}](./表格说明/{name})")
    lines.append("")
    (GUIDE_DIR / "README.md").write_text("\n".join(lines), encoding="utf-8")


