def build_records():
    records = []
    for i, (category, q, a, tags) in enumerate(RAW, start=1):
        records.append({
            "id": f"WS556-QA-{i:03d}",
            "category": category,
            "question": q,
            "answer": a,
            "source": SOURCE,
            "source_id": "WS/T 556—2017",
            "tags": [t.strip() for t in tags.split(",") if t.strip()],
        })
    return records


def write_json(records, path: Path):
    payload = {
        "dataset": "老年人膳食指导QA",
        "standard": SOURCE,
        "version": "1.0",
        "count": len(records),
        "items": records,
    }
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")


def write_xlsx(records, path: Path):
    wb = Workbook()
    ws = wb.active
    ws.title = "QA"

    headers = ["id", "category", "question", "answer", "source", "source_id", "tags"]
    header_fill = PatternFill("solid", fgColor="1F4E79")
    header_font = Font(color="FFFFFF", bold=True)
    wrap = Alignment(wrap_text=True, vertical="top")

    for col, h in enumerate(headers, 1):
        cell = ws.cell(1, col, h)
        cell.fill = header_fill
        cell.font = header_font
        cell.alignment = Alignment(horizontal="center", vertical="center")

    for row, r in enumerate(records, 2):
        values = [
            r["id"],
            r["category"],
            r["question"],
            r["answer"],
            r["source"],
            r["source_id"],
            "、".join(r["tags"]),
        ]
        for col, val in enumerate(values, 1):
            cell = ws.cell(row, col, val)
            cell.alignment = wrap

    widths = [14, 14, 42, 70, 36, 18, 24]
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.row_dimensions[1].height = 22
    ws.freeze_panes = "A2"
    ws.auto_filter.ref = f"A1:G{len(records) + 1}"

    # category summary sheet
    ws2 = wb.create_sheet("分类统计")
    ws2["A1"] = "category"
    ws2["B1"] = "count"
    ws2["A1"].fill = header_fill
    ws2["B1"].fill = header_fill
    ws2["A1"].font = header_font
    ws2["B1"].font = header_font
    from collections import Counter
    counts = Counter(r["category"] for r in records)
    for i, (cat, cnt) in enumerate(sorted(counts.items()), 2):
        ws2.cell(i, 1, cat)
        ws2.cell(i, 2, cnt)
    ws2.column_dimensions["A"].width = 16
    ws2.column_dimensions["B"].width = 10

    wb.save(path)


def main():
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    records = build_records()
    json_path = OUT_DIR / "老年人膳食指导_QA.json"
    xlsx_path = OUT_DIR / "老年人膳食指导_QA.xlsx"
    write_json(records, json_path)
    write_xlsx(records, xlsx_path)
    print(f"QA count: {len(records)}")
    print(f"JSON: {json_path}")
    print(f"XLSX: {xlsx_path}")


if __name__ == "__main__":
    main()
