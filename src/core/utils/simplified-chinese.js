/**
 * 将文本中的繁体中文转换为简体中文
 * @param {string} text - 原始文本（可能含繁体）
 * @returns {string} 转换后的简体中文
 */
export function toSimplified(text) {
  if (!text || typeof text !== 'string') return text || '';
  let result = '';
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    result += TRAD_TO_SIM[ch] || ch;
  }
  return result;
}

/**
 * 检测文本中繁体字占比
 * @param {string} text
 * @returns {number} 0-1 的比例值
 */
export function traditionalRatio(text) {
  if (!text) return 0;
  const cjkChars = text.match(/[\u4e00-\u9fff]/g) || [];
  if (cjkChars.length === 0) return 0;
  let tradCount = 0;
  for (const ch of cjkChars) {
    if (TRAD_TO_SIM[ch] && TRAD_TO_SIM[ch] !== ch) tradCount++;
  }
  return tradCount / cjkChars.length;
}

/**
 * 批量转换对象中所有字符串字段（递归）
 * @param {*} obj - 任意对象/数组/字符串
 * @returns {*} 转换后的同结构对象
 */
export function toSimplifiedDeep(obj) {
  if (typeof obj === 'string') return toSimplified(obj);
  if (Array.isArray(obj)) return obj.map(toSimplifiedDeep);
  if (obj && typeof obj === 'object') {
    const result = {};
    for (const key of Object.keys(obj)) {
      result[key] = toSimplifiedDeep(obj[key]);
    }
    return result;
  }
  return obj;
}
